// Generates the Phase 8 seed migration from docs/saleem-v2/data/*.csv (187 draft rules, 19 sources) and the
// legal-review checklist. Usage: node backend/scripts/gen-saudi-rules.mjs
// Arabic text is copied exactly. Every rule is a draft (review_state 'draft'; HAJ 'archived' until the season's
// instructions are updated). Nothing is marked legally reviewed.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const read = (f) => fs.readFileSync(path.join(root, f), "utf8").replace(/^﻿/, "");

/** RFC 4180 CSV (quoted fields, commas and newlines inside quotes). */
function parseCsv(text) {
  const rows = [];
  let row = [], field = "", q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') q = false;
      else field += c;
    } else if (c === '"') q = true;
    else if (c === ",") { row.push(field); field = ""; }
    else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(field); field = "";
      if (row.some((x) => x !== "")) rows.push(row);
      row = [];
    } else field += c;
  }
  if (field !== "" || row.length) { row.push(field); rows.push(row); }
  const [head, ...body] = rows;
  return body.map((r) => Object.fromEntries(head.map((h, i) => [h.trim(), (r[i] ?? "").trim()])));
}

const rules = parseCsv(read("docs/saleem-v2/data/saleem_saudi_rules_v0_1.csv"));
const sources = parseCsv(read("docs/saleem-v2/data/saleem_regulatory_sources.csv"));
if (rules.length !== 187) throw new Error(`expected 187 rules, got ${rules.length}`);
if (sources.length !== 19) throw new Error(`expected 19 sources, got ${sources.length}`);

const AUTH = {
  "البنك المركزي السعودي": "SAMA", "هيئة السوق المالية": "CMA", "وزارة التجارة": "MC", "الهيئة العامة لتنظيم الإعلام": "GMEDIA",
  "سدايا": "SDAIA", "الهيئة العامة للعقار": "REGA", "الهيئة العامة للغذاء والدواء": "SFDA", "وزارة الحج والعمرة": "MOHU", "وزارة السياحة": "MT",
};
const auth = (a) => AUTH[a] ?? "OTHER";
const lit = (s) => (s === null || s === undefined || s === "" ? "null" : `'${String(s).replace(/'/g, "''")}'`);
const arr = (a) => `array[${a.map(lit).join(", ")}]::text[]`;
const srcId = (id) => `sa:${id}`;
const pack = (sector) => `sa-${sector.toLowerCase()}`;

// Pack scope: organisation sector for regulated sectors; content signals or channels for cross-cutting packs.
const SCOPE = {
  BANK: { applicability: { sectors: ["banking", "finance_company", "payments"] }, sectors: ["banking", "finance_company", "payments"] },
  CMA: { applicability: { sectors: ["capital_market"] }, sectors: ["capital_market"] },
  // Cross-sector packs apply only when the ad shows the signal (signals.ts), so an enabled pack never fires on
  // unrelated ads: discounts, competitions/prize draws, direct marketing with personal data, influencer distribution.
  SALE: { triggers: ["discount_sale"] },
  MEDIA: { applicability: { distribution: ["influencer"] } },
  COMP: { triggers: ["contest_or_prize"] },
  PD: { triggers: ["direct_marketing"] },
};
const KIND = { content: ["llm", "potential_risk"], hybrid: ["hybrid", "needs_evidence"], document: ["workflow", "needs_evidence"], workflow: ["workflow", null] };
const CATEGORY = { BANK: "finance", CMA: "securities" };

const out = [];
out.push(`-- v2 Phase 8: Saudi rules v0.1 from docs/saleem-v2/data (generated by backend/scripts/gen-saudi-rules.mjs — do not edit).
-- 187 draft rules in 15 sector packs and 19 sources. All drafts pending legal review; HAJ archived until the season's
-- instructions are updated. Packs are off by default; an organisation opts in to draft packs for evaluation.
alter table public.regulatory_sources drop constraint if exists regulatory_sources_authority_check;
alter table public.regulatory_sources add constraint regulatory_sources_authority_check
  check (authority in ('SAMA', 'CMA', 'IA', 'MC', 'GMEDIA', 'SDAIA', 'INTERNAL', 'REGA', 'SFDA', 'MOHU', 'MT', 'OTHER'));
alter table public.rule_packs drop constraint if exists rule_packs_authority_check;
alter table public.rule_packs add constraint rule_packs_authority_check
  check (authority in ('SAMA', 'CMA', 'IA', 'MC', 'GMEDIA', 'SDAIA', 'INTERNAL', 'REGA', 'SFDA', 'MOHU', 'MT', 'OTHER'));
alter table public.rules add column if not exists check_mode text null check (check_mode in ('content', 'document', 'workflow', 'hybrid'));
alter table public.rules add column if not exists evidence_policy_ar text null;
alter table public.rules add column if not exists applicability_ar text null;
alter table public.rules add column if not exists csv_activation_status text null;
alter table public.regulatory_sources add column if not exists research_note_ar text null;
`);

out.push("insert into public.regulatory_sources (id, authority, title_ar, url, status, verification, notes, research_note_ar) values");
out.push(sources.map((s) => `  (${lit(srcId(s.source_id))}, ${lit(auth(s.authority_ar))}, ${lit(s.title_ar)}, ${lit(s.url)}, ${lit(s.source_type === "official_guide" ? "guideline" : "unknown")}, 'official_status_unconfirmed', ${lit([s.version_note, s.scope_ar].filter(Boolean).join(" — "))}, ${lit(s.research_note_ar)})`).join(",\n") + "\non conflict (id) do nothing;\n");

const sectors = [...new Map(rules.map((r) => [r.sector_code, r])).values()];
out.push("insert into public.rule_packs (code, authority, name_ar, name_en, description_ar, default_sectors, enabled_by_default, always_enabled) values");
out.push(sectors.map((r) => `  (${lit(pack(r.sector_code))}, ${lit(auth(r.authority_ar))}, ${lit(`${r.sector_ar} (مسودة)`)}, ${lit(`${r.sector_code} (draft)`)}, ${lit(r.sector_code === "HAJ" ? "يلزم تحديث تعليمات الموسم — معطّلة." : "قواعد مرشّحة من بحث v0.1، قيد المراجعة القانونية.")}, ${arr(SCOPE[r.sector_code]?.sectors ?? [])}, false, false)`).join(",\n") + "\non conflict (code) do nothing;\n");

out.push(`insert into public.rules (code, rulebook_version_id, category, pack, regulatory_source_id, article_ref, title_ar, title_en, summary_ar,
  check_kind, check_type, finding_type_on_fail, default_severity, applicability, content_triggers, llm_instructions, review_state,
  description_ar, description_en, source_name, source_url, check_mode, evidence_policy_ar, applicability_ar, csv_activation_status, is_active) values`);
out.push(rules.map((r) => {
  const [kind, ft] = KIND[r.check_mode] ?? KIND.content;
  const sc = SCOPE[r.sector_code] ?? {};
  const instr = `طبّق فقط إذا انطبق: ${r.applicability_ar}. الفحص: ${r.check_ar}. سياسة الدليل: ${r.evidence_policy_ar}`;
  return `  (${lit(r.rule_id)}, '22222222-2222-2222-2222-222222222222', ${lit(CATEGORY[r.sector_code] ?? "commerce")}, ${lit(pack(r.sector_code))}, ${lit(srcId(r.source_id))}, ${lit(r.legal_reference)}, ${lit(r.check_ar)}, ${lit(r.rule_id)}, ${lit(r.check_ar)},
   ${lit(kind)}, 'hybrid', ${lit(ft)}, ${lit(r.internal_priority === "high" ? "violation" : "warning")}, ${lit(JSON.stringify(sc.applicability ?? {}))}::jsonb, ${arr(sc.triggers ?? [])}, ${lit(instr)}, ${lit(r.sector_code === "HAJ" ? "archived" : "draft")},
   ${lit(r.check_ar)}, ${lit(r.rule_id)}, ${lit(r.source_title_ar)}, ${lit(r.source_url)}, ${lit(r.check_mode)}, ${lit(r.evidence_policy_ar)}, ${lit(r.applicability_ar)}, ${lit(r.activation_status)}, true)`;
}).join(",\n") + "\non conflict do nothing;\n");

fs.writeFileSync(path.join(root, "backend/supabase/migrations/20261118080100_v2_saudi_rules_v0_1.sql"), out.join("\n"));

// Legal-review checklist grouped by sector.
const doc = [`# قائمة المراجعة القانونية — القواعد السعودية v0.1

مولّدة من \`docs/saleem-v2/data/saleem_saudi_rules_v0_1.csv\` بالأمر \`node backend/scripts/gen-saudi-rules.mjs\`.
**كل القواعد مسودات** (لم يُراجَع أي منها قانونياً). لا تُفعَّل قاعدة إلا بعد هذه المراجعة وإصدار جديد ينشره مشرف المنصة.
قواعد الحج والعمرة معطّلة: يلزم تحديث تعليمات الموسم.
`];
for (const s of sectors) {
  doc.push(`\n## ${s.sector_ar} — \`${pack(s.sector_code)}\`\n\n| الرمز | الفحص | المرجع | المصدر | نوع الفحص | القرار |\n|---|---|---|---|---|---|`);
  for (const r of rules.filter((x) => x.sector_code === s.sector_code))
    doc.push(`| ${r.rule_id} | ${r.check_ar} | ${r.legal_reference} | [${r.source_title_ar}](${r.source_url}) | ${r.check_mode} | ☐ |`);
}
doc.push("\n\n## المصادر\n\n| المعرّف | الجهة | العنوان | ملاحظة البحث |\n|---|---|---|---|");
for (const s of sources) doc.push(`| ${s.source_id} | ${s.authority_ar} | [${s.title_ar}](${s.url}) | ${s.research_note_ar} |`);
doc.push("\nالمراجع: ______________  التاريخ: ________  التوقيع: ______________\n");
fs.writeFileSync(path.join(root, "docs/saleem-v2/legal/LEGAL_REVIEW_CHECKLIST.md"), doc.join("\n"));
console.log(`rules ${rules.length}, sources ${sources.length}, packs ${sectors.length}`);
