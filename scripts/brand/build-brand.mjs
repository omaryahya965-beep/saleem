// Builds SALEEM brand assets from the traced logo (scripts/brand/trace-logo.cjs → trace.json):
//   frontend/src/components/ui/brandPaths.ts (inline SVG paths for <Brand/>)
//   frontend/public/brand/saleem-logo{,-inverse}.svg, saleem-mark.svg, favicon.svg,
//   favicon-32.png, icon-192.png, icon-512.png, apple-touch-icon.png, favicon.ico (rendered with Playwright).
// Usage (from frontend/): node ../scripts/brand/trace-logo.cjs <repo> ../docs/brand/saleem-logo-source.png <tmp>/trace.json
//                         node ../scripts/brand/build-brand.mjs <tmp>/trace.json
import fs from "node:fs";
import path from "node:path";
import { chromium } from "@playwright/test";

const t = JSON.parse(fs.readFileSync(process.argv[2], "utf8"));
const root = path.resolve(import.meta.dirname, "../..");
const pub = path.join(root, "frontend/public");
fs.mkdirSync(path.join(pub, "brand"), { recursive: true });

// The logo's own inks, flattened (no gradients): forest-green wordmark and lower stroke, gold upper stroke.
// On dark surfaces: cream wordmark, mint lower stroke, brand gold upper stroke.
const C = {
  word: t.colours.word,
  green: t.colours.markGreen,
  gold: t.colours.markGold,
  // Gold sheen of the supplied artwork (top → bottom of the upper stroke).
  goldTop: "#c9b178",
  goldBottom: "#9c8149",
  cream: "#f7f3ea",
  greenOnDark: "#7fd1ae",
  goldOnDark: "#c9a86a",
};
const [x0, y0, x1, y1] = t.bbox;
const pad = 4;
const vb = `${x0 - pad} ${y0 - pad} ${x1 - x0 + pad * 2} ${y1 - y0 + pad * 2}`;
const [m0, n0, m1, n1] = t.markBox;
const side = Math.max(m1 - m0, n1 - n0);
const mvb = (p) =>
  `${(m0 + m1) / 2 - side / 2 - p} ${(n0 + n1) / 2 - side / 2 - p} ${side + p * 2} ${side + p * 2}`;

const svg = (viewBox, body, label = "سليم — SALEEM") =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" role="img" aria-label="${label}">${body}</svg>\n`;
const path_ = (fill, d) =>
  `<path fill="${fill}" fill-rule="evenodd" d="${d}"/>`;
const sheen = `<defs><linearGradient id="g" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="${C.goldTop}"/><stop offset="1" stop-color="${C.goldBottom}"/></linearGradient></defs>`;
const mark = (green, gold) =>
  (gold === "url(#g)" ? sheen : "") +
  path_(green, t.markGreen) +
  path_(gold, t.markGold);

fs.writeFileSync(
  path.join(pub, "brand/saleem-logo.svg"),
  svg(vb, path_(C.word, t.word) + mark(C.green, "url(#g)")),
);
fs.writeFileSync(
  path.join(pub, "brand/saleem-logo-inverse.svg"),
  svg(vb, path_(C.cream, t.word) + mark(C.greenOnDark, C.goldOnDark)),
);
fs.writeFileSync(
  path.join(pub, "brand/saleem-mark.svg"),
  svg(mvb(12), mark(C.green, "url(#g)")),
);
fs.writeFileSync(
  path.join(pub, "favicon.svg"),
  svg(mvb(18), mark(C.green, "url(#g)")),
);

fs.writeFileSync(
  path.join(root, "frontend/src/components/ui/brandPaths.ts"),
  `// Generated by scripts/brand/build-brand.mjs from docs/brand/saleem-logo-source.png — do not edit by hand.
export const LOGO_VIEWBOX = "${vb}";
export const MARK_VIEWBOX = "${mvb(6)}";
export const LOGO_COLORS = ${JSON.stringify(C, null, 2)} as const;
export const WORDMARK_PATH =
  "${t.word}";
export const MARK_GREEN_PATH =
  "${t.markGreen}";
export const MARK_GOLD_PATH =
  "${t.markGold}";
`,
);

// Raster icons: the symbol centred on cream (app icons) or transparent (favicon).
const browser = await chromium.launch();
const page = await browser.newPage();
async function png(size, bg, file, padRatio) {
  const inner = svg(mvb(Math.round(side * padRatio)), mark(C.green, "url(#g)"));
  await page.setViewportSize({ width: size, height: size });
  await page.setContent(
    `<style>html,body{margin:0;background:${bg}}svg{display:block;width:${size}px;height:${size}px}</style>${inner}`,
  );
  const buf = await page.screenshot({
    omitBackground: bg === "transparent",
    type: "png",
  });
  if (file) fs.writeFileSync(path.join(pub, file), buf);
  return buf;
}
await png(32, "transparent", "brand/favicon-32.png", 0.04);
await png(192, C.cream, "brand/icon-192.png", 0.16);
await png(512, C.cream, "brand/icon-512.png", 0.16);
await png(180, C.cream, "apple-touch-icon.png", 0.16);
const imgs = [];
for (const s of [16, 32, 48])
  imgs.push([s, await png(s, "transparent", null, 0.04)]);
const head = Buffer.alloc(6 + 16 * imgs.length);
head.writeUInt16LE(0, 0);
head.writeUInt16LE(1, 2);
head.writeUInt16LE(imgs.length, 4);
let off = head.length;
imgs.forEach(([s, b], i) => {
  const o = 6 + i * 16;
  head.writeUInt8(s, o);
  head.writeUInt8(s, o + 1);
  head.writeUInt16LE(1, o + 4);
  head.writeUInt16LE(32, o + 6);
  head.writeUInt32LE(b.length, o + 8);
  head.writeUInt32LE(off, o + 12);
  off += b.length;
});
fs.writeFileSync(
  path.join(pub, "favicon.ico"),
  Buffer.concat([head, ...imgs.map(([, b]) => b)]),
);
await browser.close();
console.log("brand assets written", C);
