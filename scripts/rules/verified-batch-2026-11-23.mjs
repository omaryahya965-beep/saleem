function activate(code, [article, text, appl], source, url, reason) {
  return `update public.rules set
  review_state = 'active', legal_status = 'legally_reviewed', source_verified = true,
  official_text_ar = ${q(text)}, article_ref = ${q(article)},
  applicability_ar = coalesce(nullif(applicability_ar, ''), ${q(appl)}),
  regulatory_source_id = ${q(source)}, source_url = ${q(url)},
  legal_reviewed_by = ${q(REVIEWER)}, legal_reviewed_at = now(), change_reason = ${q(reason)}
where ${where(code)};`;
}
function archive(code, reason) {
  return `update public.rules set review_state = 'archived', change_reason = ${q(reason)} where ${where(code)};`;
}

